// Os operadores são usados ​​para realizar operações em variáveis ​​e valores.

 public class Operadores {

    public static void main(String[] args) {

        int x = 10;
        int y = 3;

        System.out.println(x + y); // Soma = 13

        System.out.println(x - y); // Subtração = 7

        System.out.println(x * y); // Multiplicação = 30

        System.out.println(x / y); // Divisão = 3

        System.out.println(x % y); // 1

        int z = 5;
        ++z; // Adiciona +1 ao inteiro. Utlizado em loopings.

        System.out.println(z); // 6
        --z; // Subtrai -1 ao inteiro. Utilizado em loopings.

}
}

